#!/usr/bin/env python3
"""Embed Sorter.Updater into both native GUI executables to avoid stale helper mismatches."""
from pathlib import Path
import json
root=Path(__file__).resolve().parent
payload=(root.parent/'Sorter.Updater').read_text(encoding='utf-8')
assert '\x00' not in payload
assert len(payload)<100_000
lines=payload.splitlines(keepends=True)
source='/* Generated by sync_updater.py; edit ../Sorter.Updater instead. */\n'
source+='static const char su_embedded_updater[] =\n'
source+='\n'.join('    '+json.dumps(line,ensure_ascii=True) for line in lines)+';\n'
(root/'sorter_updater_embedded.h').write_text(source,encoding='utf-8')
print(f'Embedded {len(payload.encode())} Python bytes in sorter_updater_embedded.h')
