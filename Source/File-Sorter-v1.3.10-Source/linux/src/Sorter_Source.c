static int read_watched_count(void) {
    FILE *fp=fopen(dirs_file,"r");
    if(!fp)return 0;
    char *line=NULL;size_t cap=0;int count=0;
    while(getline(&line,&cap,fp)>0) {
        size_t len=strlen(line);
        while(len&&(line[len-1]=='\n'||line[len-1]=='\r'))line[--len]=0;
        if(len>0 && (line[0]=='/'||(line[0]=='~' && line[1]=='/')))count++;
    }
    free(line);fclose(fp);
    return count;
}
static void refresh_config(int first) {
    struct stat state;
    int present=(stat(dirs_file,&state)==0 && S_ISREG(state.st_mode));
    if(!first && present==dirs_present && (!present || (state.st_ino==dirs_inode && state.st_dev==dirs_device)))return;
    dirs_present=present;
    dirs_inode=present?state.st_ino:0;
    dirs_device=present?state.st_dev:0;
    watched_count=present?read_watched_count():0;
    if(!first){
        if(present)add_log("Watched-folder settings updated by config editor.");
        else add_log("No watched-folder configuration. Open the config editor.");
    }
    needs_redraw=1;
}
static void refresh_interval_label(void){
    char new_value[64]="2";
    FILE *f=fopen(interval_file,"r");
    if(f){
        char candidate[64]={0};
        if(fgets(candidate,sizeof(candidate),f)){
            candidate[strcspn(candidate,"\r\n")]=0;
            int good=candidate[0]!=0,positive=0;
            for(const char *c=candidate;*c;c++){
                if(*c>='1'&&*c<='9')positive=1;
                if(!((*c>='0'&&*c<='9')||*c=='.'))good=0;
            }
            if(good&&positive)snprintf(new_value,sizeof(new_value),"%s",candidate);
        }
        fclose(f);
    }
    if(strcmp(new_value,interval_display)){
        snprintf(interval_display,sizeof(interval_display),"%s",new_value);
        needs_redraw=1;
    }
}
